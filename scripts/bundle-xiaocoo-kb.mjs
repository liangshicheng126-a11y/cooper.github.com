#!/usr/bin/env node
/**
 * Bundle content/xiaocoo/*.md into TS modules for Next API + Cloudflare Worker.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const kbDir = path.join(root, "content", "xiaocoo");
const order = ["system.md", "profile.md", "projects.md", "voice.md", "faq.md"];

const parts = order.map((file) => {
  const full = path.join(kbDir, file);
  if (!fs.existsSync(full)) {
    throw new Error(`Missing knowledge file: ${file}`);
  }
  return fs.readFileSync(full, "utf8").trim();
});

const knowledge = parts.join("\n\n---\n\n");
const escaped = JSON.stringify(knowledge);

const banner = `/** Auto-generated by scripts/bundle-xiaocoo-kb.mjs — do not edit by hand. */\n`;
const body = `${banner}export const XIAOCOO_KNOWLEDGE = ${escaped} as const;\n`;

const targets = [
  path.join(root, "src", "lib", "xiaocoo", "bundledKnowledge.ts"),
  path.join(root, "workers", "xiaocoo", "src", "knowledge.ts"),
];

for (const target of targets) {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, body, "utf8");
  console.log(`Wrote ${path.relative(root, target)}`);
}
